#!/usr/bin/env node
// Generates the compact typed tables in src/data/gen/ from research/*.json.
// Usage: node scripts/gen-data.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const research = (name) => JSON.parse(readFileSync(join(root, 'research', name), 'utf8'));
const outDir = join(root, 'src', 'data', 'gen');
mkdirSync(outDir, { recursive: true });

const HEADER = '// Generated by scripts/gen-data.mjs from research/*.json. Do not edit by hand.\n';
const hex = (s) => parseInt(s, 16);

function emit(file, imports, body) {
  writeFileSync(join(outDir, file), HEADER + (imports ? imports + '\n' : '') + '\n' + body + '\n');
  console.log('wrote src/data/gen/' + file);
}

// ---------------------------------------------------------------- models

const FRIENDLY = {
  '0xFE24:101': 'Magger68',
  '0xFE25:102': 'Magger68 Pro',
  '0xFC67:109': 'Magger68 Plus',
  '0xFC66:110': 'Magger68 Ultra',
  '0xFC60:112': 'Magger68 Ultra JIS',
  '0xFB37:114': 'Magger 60 (K60_1 layout)',
  '0xFB38:115': 'Magger 60',
  '0xFB48:117': 'Magger 60 (FB48)',
  '0xFB49:118': 'Magger 60 (2404)',
  '0xFC64:107': 'LUMINKEY K65',
  '0xFC65:108': 'LUMINKEY K75',
  '0xFC63:111': 'BLA75',
  '0xFB3F:116': 'BLA75 (FB3F)',
  '0xFB54:119': 'GLASS 80HE',
  '0x3635:120': 'LUMINKEY K80',
};
const MAGGER68_TYPES = [101, 102, 109, 110, 112];
const MAGGER60_TYPES = [114, 115, 117, 118];
const RT_PRECISION_TYPES = [107, 108, 109, 110, 111, 112, 114, 115, 116, 117, 118, 119];
const ADVANCED = ['dks', 'mt', 'tgl', 'rs', 'socd', 'oks'];

function features(entry) {
  const f = entry.features;
  const isMagger = MAGGER68_TYPES.includes(entry.type) || MAGGER60_TYPES.includes(entry.type);
  const coarse = entry.type === 101 || entry.type === 102;
  const rawPerMm = coarse ? 50 : 100;
  const rtPrecisionModes = RT_PRECISION_TYPES.includes(entry.type)
    ? Object.entries(f.rtPrecisionModes).map(([id, m]) => ({
        id: Number(id),
        stepMm: m.step_mm,
        rawPerMm: m.rawPerMm,
        maxRaw: m.maxRaw,
      }))
    : // 0.02 mm models: the official UI caps RT at rtMaxTravel = 110 (2.2 mm).
      [{ id: 0, stepMm: 1 / rawPerMm, rawPerMm, maxRaw: coarse ? 110 : 220 }];
  return {
    // The official app forces profile 0 for types 116-118; treated as a bug for Magger models.
    profiles: isMagger ? 4 : typeof f.profiles === 'number' ? f.profiles : 1,
    layers: f.layers,
    travel: {
      rawPerMm,
      maxRaw: f.switchMaxTravelRaw_default ?? (coarse ? 170 : 340),
      minActuationRaw: f.minActuationRaw ?? (coarse ? 4 : 9),
      deadzoneMaxRaw: f.deadzoneMaxRaw ?? (coarse ? 25 : 50),
    },
    rtPrecisionModes,
    switchTypes: f.switchTypes,
    advanced: ADVANCED.filter((k) => f.advancedKeys.includes(k)),
    macros: f.advancedKeys.includes('macro'),
    lighting: f.tabs.includes('light'),
    perKeyRgb: f.perKeyRGB === true,
    liveTravel: f.liveTravelDebugMode === true,
    calibration: f.calibration === true,
    jis: f.jisKeyNames === true,
    pollingRates: Object.entries(f.reportRateOptionsHz).map(([v, hz]) => ({ value: Number(v), hz })),
  };
}

function buildModels() {
  const dev = research('devices.json');
  const bootPids = new Set(dev.bootloaderModePIDs.map(hex));
  const entries = [];
  for (const [key, value] of Object.entries(dev.devices)) {
    const pidStr = key.split('_')[1];
    for (const e of Array.isArray(value) ? value : [value]) entries.push({ ...e, pidStr, pid: hex(pidStr) });
  }
  const isNormal = (e) => e.hidFilter.usagePage === 1;
  const models = [];
  for (const e of entries.filter(isNormal)) {
    const family = MAGGER68_TYPES.includes(e.type) ? 'Magger68' : MAGGER60_TYPES.includes(e.type) ? 'Magger 60' : 'Other';
    models.push({
      name: FRIENDLY[`${e.pidStr}:${e.type}`] ?? e.productName ?? e.name,
      family,
      id: e.id,
      type: e.type,
      pid: e.pid,
      bootPid: 0,
      layoutId: e.layout,
      latestFw: e.fwVersion,
      features: features(e),
      altPids: [],
      productNames: e.productName ? [e.productName] : [],
    });
  }
  for (const e of entries.filter((x) => !isNormal(x))) {
    const owner = models.find((m) => m.id === e.id && m.type === e.type && !m.productNames.some((n) => n.endsWith('2.4G')));
    if (!owner) throw new Error('no model for secondary PID ' + e.pidStr);
    if (bootPids.has(e.pid)) owner.bootPid = e.pid;
    else owner.altPids.push(e.pid); // second PID that is not a bootloader (e.g. 2.4G config interface)
  }
  const rank = { Magger68: 0, 'Magger 60': 1, Other: 2 };
  models.sort((a, b) => rank[a.family] - rank[b.family]);
  return models;
}

// ---------------------------------------------------------------- layouts

/** N(): the code the official app derives from a default-keymap entry (see layouts.json _doc). */
function entryCode(c) {
  if (c.type === 240 && c.code1 === 255) return 255;
  if (c.type !== 16) return -1;
  if (c.code >= 224 && c.code <= 231) return c.code;
  const bits = [1, 2, 4, 8, 16, 32, 64, 128];
  const bit = bits.indexOf(c.code1);
  if (bit >= 0 && (c.code2 === 0 || c.code2 === c.code1 << 8)) return 224 + bit;
  return c.code2;
}

function buildLayout(id, l) {
  const defaults = (l.defaultCodes ?? []).map(entryCode);
  const keys = l.keys.map((k) => ({ ...k }));
  if (!l.defaultCodes) keys.forEach((k, i) => (k.demoIndex = i)); // no demo data: layout order
  for (const k of keys) {
    if (k.demoIndex != null && defaults[k.demoIndex] !== undefined && defaults[k.demoIndex] !== k.code)
      throw new Error(`${id}: key ${k.i} code ${k.code} != default slot ${k.demoIndex}`);
  }
  const used = new Set(keys.map((k) => k.demoIndex).filter((x) => x != null));
  for (const k of keys) {
    if (k.demoIndex != null) continue;
    let slot = 0;
    while (used.has(slot) || (defaults[slot] ?? 0) > 0) slot++;
    k.demoIndex = slot; // synthetic slot for keys the site's demo data does not cover
    used.add(slot);
  }
  for (const k of keys) defaults[k.demoIndex] = k.code;
  for (let i = 0; i < defaults.length; i++) if (defaults[i] === undefined || defaults[i] < 0) defaults[i] = 0;
  return {
    id,
    width: l.width,
    height: l.height,
    keys: keys.map((k) => [k.label, k.x, k.y, k.w, k.h, k.code, k.demoIndex]),
    defaults,
  };
}

// ---------------------------------------------------------------- keycodes / lighting

function buildKeycodes() {
  const kc = research('keycodes.json');
  const special = {};
  for (const s of kc.special_type240) special[`${s.code1},${s.code2}`] ??= s.label;
  for (const s of kc.pickerCategories.special.keys) if (s.type === 240) special[`${s.code1},${s.code2}`] ??= s.name;
  const consumer = {};
  for (const c of kc.consumer_type48) consumer[c.code1 | (c.code2 << 8)] = c.label;
  const jis = {};
  for (const k of kc.hidKeyboard_JIS_labels_types112_124) jis[k.usage] ??= k.label;
  const pick = (list) => list.map((k) => [k.type, k.code1, k.code2]);
  return {
    special,
    consumer,
    jis,
    pickerMedia: pick(kc.pickerCategories.media),
    pickerLighting: pick(kc.pickerCategories.lighting),
    pickerSpecial: pick(kc.pickerCategories.special.keys.filter((k) => !(k.type === 240 && k.code1 === 255))),
  };
}

function buildLighting() {
  const lt = research('lighting.json');
  return lt.effects.map((e) => ({
    id: e.id,
    name: e.name,
    speed: e.speed,
    brightness: e.brightness,
    color: e.color,
    multicolor: e.palette,
    direction: e.direction,
  }));
}

// ---------------------------------------------------------------- emit

const json = (v) => JSON.stringify(v);

const models = buildModels();
emit(
  'models.ts',
  "import type { DeviceModel } from '../../core/types';",
  'export interface ModelRecord extends DeviceModel {\n' +
    '  /** Extra normal-mode PIDs (e.g. a second config interface). */\n  altPids: number[];\n' +
    '  /** HIDDevice.productName values that select this entry when several share a PID. */\n  productNames: string[];\n}\n\n' +
    'export const VENDOR_ID = 0x19f5;\n\n' +
    'export const MODELS: ModelRecord[] = [\n' +
    models.map((m) => '  ' + json(m) + ',').join('\n') +
    '\n];',
);

const layouts = Object.entries(research('layouts.json').layouts).map(([id, l]) => buildLayout(id, l));
emit(
  'layouts.ts',
  '',
  '/** Key tuple: [label, x, y, w, h, code, demoIndex]. `defaults[slot]` = N() code of the default layer-0 keymap. */\n' +
    'export type KeyTuple = [string, number, number, number, number, number, number];\n' +
    'export interface LayoutData {\n  id: string;\n  width: number;\n  height: number;\n  keys: KeyTuple[];\n  defaults: number[];\n}\n\n' +
    'export const LAYOUTS: LayoutData[] = [\n' +
    layouts.map((l) => '  ' + json(l) + ',').join('\n') +
    '\n];',
);

const kc = buildKeycodes();
emit(
  'keycodes.ts',
  '',
  '/** Labels of type-240 special keys, keyed "code1,code2". */\n' +
    `export const SPECIAL_LABELS: Record<string, string> = ${json(kc.special)};\n\n` +
    '/** Consumer (HID page 0x0C) usage -> label. */\n' +
    `export const CONSUMER_LABELS: Record<number, string> = ${json(kc.consumer)};\n\n` +
    '/** JIS legends for HID usages (types 112/124). */\n' +
    `export const JIS_LABELS: Record<number, string> = ${json(kc.jis)};\n\n` +
    '/** Picker lists from the official site as [type, code1, code2]. */\n' +
    `export const PICKER_MEDIA: [number, number, number][] = ${json(kc.pickerMedia)};\n` +
    `export const PICKER_LIGHTING: [number, number, number][] = ${json(kc.pickerLighting)};\n` +
    `export const PICKER_SPECIAL: [number, number, number][] = ${json(kc.pickerSpecial)};`,
);

emit(
  'lighting.ts',
  '',
  'export interface LightEffect {\n  id: number;\n  name: string;\n  speed: boolean;\n  brightness: boolean;\n  color: boolean;\n' +
    '  /** Effect offers the multicolor (rainbow) option. */\n  multicolor: boolean;\n' +
    '  /** Direction control set: 0 none, 1 right/left, 2 down/up, 3 outward/inward, 4 ccw/cw. */\n  direction: 0 | 1 | 2 | 3 | 4;\n}\n\n' +
    'export const EFFECTS: LightEffect[] = [\n' +
    buildLighting().map((e) => '  ' + json(e) + ',').join('\n') +
    '\n];',
);
